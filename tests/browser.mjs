import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('.impeccable/review',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
const appURL=process.env.APP_URL||'http://127.0.0.1:3000';
try {
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[],externalRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',req=>{if(new URL(req.url()).origin!==new URL(appURL).origin)externalRequests.push(req.url());});
  await page.goto(appURL);
  await page.getByRole('button',{name:'Place paper trade'}).waitFor();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Coach',exact:true}).click();
  await page.getByRole('heading',{name:'Plan before you enter'}).waitFor();
  assert.equal(await page.locator('input[type=password]').count(),0);
  assert.equal(await page.getByRole('button',{name:'Ask coach',exact:true}).count(),0);
  await page.getByRole('button',{name:'Check my risk'}).click();
  await page.getByText(/calculator allows 39 shares/).waitFor();
  await page.getByRole('button',{name:'Save plan & place paper trade'}).click();
  await page.getByRole('alert').filter({hasText:'Complete all three'}).waitFor();
  for(const label of ['I checked the trend','I know the stop price','I accept the planned loss'])await page.getByLabel(new RegExp(label)).check();
  const thesis='Price broke the prior high with volume. My stop below the recent low invalidates this setup.';
  await page.getByLabel('Why is this setup worth practicing?').fill(thesis);
  // A risk change requires a fresh acknowledgement, while keeping the written reasoning.
  await page.getByLabel('Risk budget',{exact:true}).selectOption('0.25');
  assert.equal(await page.getByLabel(/I accept the planned loss/).isChecked(),false);
  assert.equal(await page.getByLabel('Why is this setup worth practicing?').inputValue(),thesis);
  await page.getByLabel('Risk budget',{exact:true}).selectOption('0.5');
  for(const label of ['I checked the trend','I know the stop price','I accept the planned loss'])await page.getByLabel(new RegExp(label)).check();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/coach-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/coach-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Coach must not overflow');
  await page.getByRole('button',{name:'Save plan & place paper trade'}).click();
  await page.getByRole('heading',{name:'Your open position'}).waitFor();
  await page.getByRole('button',{name:'Coach',exact:true}).click();
  await page.getByRole('heading',{name:'Follow your plan'}).waitFor();
  await page.getByText(thesis,{exact:true}).waitFor();
  await page.getByRole('button',{name:'Manage paper position'}).click();
  for(let i=0;i<44&&await page.getByRole('button',{name:'Close paper position'}).count();i++)await page.getByRole('button',{name:'Next candle'}).click();
  assert.equal(await page.getByRole('button',{name:'Close paper position'}).count(),0);
  await page.getByRole('button',{name:/^Journal/}).click();
  await page.locator('tbody tr').first().waitFor();
  await page.getByText(thesis,{exact:true}).waitFor();
  await page.getByRole('button',{name:'Save reflection'}).click();
  await page.getByRole('alert').filter({hasText:'Choose whether'}).waitFor();
  await page.getByLabel('Did you follow your intended entry and exit plan?').selectOption('yes');
  const lesson='A qualifying setup still has an uncertain outcome.';
  await page.getByLabel('What did you learn?').fill(lesson);
  await page.getByLabel('What will you do next time?').fill('Check the volume and planned loss before my next entry.');
  await page.getByRole('button',{name:'Save reflection'}).click();
  await page.getByText('Reflection saved for this session.').waitFor();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/journal-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Journal page must not overflow');
  await page.setViewportSize({width:1440,height:1100});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/journal-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Learning guide'}).click();
  await page.getByRole('heading',{name:'Your decision-making playbook'}).waitFor();
  await page.getByRole('button',{name:/^Journal/}).click();
  assert.equal(await page.getByLabel('What did you learn?').inputValue(),lesson);
  await page.getByRole('button',{name:'Practice',exact:true}).click();
  await page.getByRole('button',{name:'Reset practice'}).click();
  await page.getByRole('button',{name:'Confirm reset & clear journal'}).click();
  await page.getByRole('button',{name:'Journal 0'}).waitFor();
  await page.getByRole('button',{name:'Place paper trade'}).click();
  await page.getByRole('button',{name:'Close paper position'}).click();
  await page.getByRole('button',{name:/^Journal/}).click();
  await page.getByText('No written plan was saved before entry.').waitFor();
  assert.equal(await page.locator('tbody tr').count(),1);
  await page.reload();
  await page.getByRole('button',{name:'Journal 0'}).waitFor();
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  await page.getByRole('link',{name:'AIAgent home'}).click();
  await page.getByRole('heading',{name:'Market lab'}).waitFor();
  assert.deepEqual(externalRequests,[],'App must not call external services');assert.deepEqual(errors,[]);
  console.log('PASS: guided plan, risk re-acknowledgement, entry, automatic exit, saved reflection, navigation, mobile layouts, quick trade, reset, no storage or external requests.');
}finally{await browser.close();}
